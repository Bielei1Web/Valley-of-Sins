CREATE OR REPLACE FUNCTION public.delete_user_chat(other_user_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
    own_user_id bigint;
BEGIN
    SELECT id INTO own_user_id
    FROM public.app_users
    WHERE auth_user_id = auth.uid() AND approved = true;

    IF own_user_id IS NULL OR own_user_id = other_user_id THEN
        RETURN;
    END IF;

    UPDATE public.user_messages
    SET deleted_by_sender = CASE
            WHEN sender_id = own_user_id THEN true ELSE deleted_by_sender END,
        deleted_by_recipient = CASE
            WHEN recipient_id = own_user_id THEN true ELSE deleted_by_recipient END
    WHERE (sender_id = own_user_id AND recipient_id = other_user_id)
       OR (sender_id = other_user_id AND recipient_id = own_user_id);
END;
$function$;

