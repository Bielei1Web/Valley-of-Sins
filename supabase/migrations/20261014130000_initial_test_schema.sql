CREATE OR REPLACE FUNCTION public.has_tab_permission(
    requested_tab text,
    requested_action text
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
    SELECT public.is_admin_user()
        OR EXISTS (
            SELECT 1
            FROM public.app_users u
            JOIN public.app_user_tab_permissions p ON p.user_id = u.id
            WHERE u.auth_user_id = auth.uid()
              AND u.approved = true
              AND p.tab_key = requested_tab
              AND (
                  (requested_action = 'view' AND p.can_view)
                  OR (requested_action = 'edit' AND p.can_edit)
                  OR (requested_action = 'delete' AND p.can_delete)
              )
        );
$function$;

CREATE OR REPLACE FUNCTION public.has_special_permission(requested_permission text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
    SELECT public.is_admin_user()
        OR EXISTS (
            SELECT 1
            FROM public.app_users
            WHERE auth_user_id = auth.uid()
              AND approved = true
              AND special_permissions @> jsonb_build_object(requested_permission, true)
        );
$function$;

