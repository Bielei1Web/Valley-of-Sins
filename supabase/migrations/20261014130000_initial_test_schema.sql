-- Valley of Sins test schema.
-- Creates application structure only; no rows, Auth users, or secrets are copied.
-- Password-reset RPCs are intentionally omitted until that flow is redesigned safely.

CREATE TABLE public.app_users (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username text NOT NULL UNIQUE,
    password_hash text,
    permission text NOT NULL DEFAULT 'view'::text,
    approved boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    is_admin boolean NOT NULL DEFAULT false,
    avatar text,
    theme text DEFAULT 'dark'::text,
    bio text,
    avatar_history jsonb DEFAULT '[]'::jsonb,
    special_permissions jsonb NOT NULL DEFAULT '{}'::jsonb,
    last_seen timestamp with time zone,
    auth_user_id uuid
);

CREATE UNIQUE INDEX app_users_auth_user_id_unique
    ON public.app_users USING btree (auth_user_id)
    WHERE auth_user_id IS NOT NULL;

CREATE TABLE public.app_user_tab_permissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    tab_key text NOT NULL,
    can_view boolean NOT NULL DEFAULT false,
    can_edit boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    can_delete boolean NOT NULL DEFAULT false,
    UNIQUE (user_id, tab_key)
);

CREATE INDEX idx_app_user_tab_permissions_user_id
    ON public.app_user_tab_permissions USING btree (user_id);

