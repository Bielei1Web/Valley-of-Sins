CREATE OR REPLACE FUNCTION public.restrict_self_profile_update()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
BEGIN
    IF auth.uid() IS NULL OR public.is_admin_user() THEN
        RETURN NEW;
    END IF;

    IF (to_jsonb(OLD) - ARRAY[
        'avatar',
        'avatar_history',
        'theme',
        'bio',
        'last_seen'
    ]) IS DISTINCT FROM
       (to_jsonb(NEW) - ARRAY[
        'avatar',
        'avatar_history',
        'theme',
        'bio',
        'last_seen'
    ]) THEN
        RAISE EXCEPTION 'Normale Benutzer dürfen nur Profilfelder ändern';
    END IF;

    RETURN NEW;
END;
$function$;

CREATE TRIGGER restrict_self_profile_update
BEFORE UPDATE ON public.app_users
FOR EACH ROW
EXECUTE FUNCTION public.restrict_self_profile_update();

CREATE OR REPLACE FUNCTION public.get_member_directory()
RETURNS TABLE(
    id bigint,
    username text,
    created_at timestamp with time zone,
    avatar text,
    bio text,
    last_seen timestamp with time zone
)
LANGUAGE sql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
    SELECT member.id, member.username, member.created_at,
           member.avatar, member.bio, member.last_seen
    FROM public.app_users AS member
    WHERE COALESCE(member.approved, true)
      AND EXISTS (
          SELECT 1
          FROM public.app_users AS viewer
          WHERE viewer.auth_user_id = auth.uid()
            AND viewer.approved = true
            AND (
                viewer.is_admin
                OR EXISTS (
                    SELECT 1
                    FROM public.app_user_tab_permissions AS permission
                    WHERE permission.user_id = viewer.id
                      AND permission.tab_key = 'mitglieder'
                      AND (permission.can_view OR permission.can_edit OR permission.can_delete)
                )
            )
      )
    ORDER BY member.username;
$function$;

CREATE OR REPLACE FUNCTION public.get_chat_group_members(target_group_id bigint)
RETURNS TABLE(id bigint, username text, avatar text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
    SELECT u.id, u.username, u.avatar
    FROM public.chat_group_members gm
    JOIN public.app_users u ON u.id = gm.user_id
    WHERE gm.group_id = target_group_id
      AND public.is_chat_group_member(target_group_id);
$function$;

CREATE OR REPLACE FUNCTION public.get_chat_group_users(target_group_id bigint)
RETURNS TABLE(id bigint, username text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
    SELECT DISTINCT u.id, u.username
    FROM public.app_users u
    WHERE public.is_chat_group_member(target_group_id)
      AND (
          EXISTS (
              SELECT 1 FROM public.chat_group_members gm
              WHERE gm.group_id = target_group_id AND gm.user_id = u.id
          )
          OR EXISTS (
              SELECT 1 FROM public.chat_group_messages m
              WHERE m.group_id = target_group_id AND m.sender_id = u.id
          )
      );
$function$;

CREATE OR REPLACE FUNCTION public.get_my_chat_groups()
RETURNS TABLE(id bigint, name text, unread_count bigint)
LANGUAGE sql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
    SELECT groups.id, groups.name,
           count(messages.id) FILTER (
               WHERE messages.sender_id <> viewer.id AND reads.message_id IS NULL
           ) AS unread_count
    FROM public.chat_groups groups
    JOIN public.chat_group_members membership ON membership.group_id = groups.id
    JOIN public.app_users viewer
      ON viewer.id = membership.user_id
     AND viewer.auth_user_id = auth.uid()
     AND viewer.approved = true
    LEFT JOIN public.chat_group_messages messages ON messages.group_id = groups.id
    LEFT JOIN public.chat_group_message_reads reads
      ON reads.message_id = messages.id
     AND reads.user_id = viewer.id
    GROUP BY groups.id, groups.name, viewer.id
    ORDER BY groups.name;
$function$;

CREATE OR REPLACE FUNCTION public.create_chat_group(
    group_name text,
    member_ids bigint[] DEFAULT '{}'::bigint[]
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
    own_id bigint;
    new_group_id bigint;
BEGIN
    SELECT id INTO own_id
    FROM public.app_users
    WHERE auth_user_id = auth.uid() AND approved = true;

    IF own_id IS NULL OR length(trim(group_name)) = 0 THEN
        RETURN NULL;
    END IF;

    INSERT INTO public.chat_groups (name, created_by)
    VALUES (trim(group_name), own_id)
    RETURNING id INTO new_group_id;

    INSERT INTO public.chat_group_members (group_id, user_id)
    VALUES (new_group_id, own_id);

    INSERT INTO public.chat_group_members (group_id, user_id)
    SELECT new_group_id, users.id
    FROM public.app_users users
    WHERE users.id = ANY(COALESCE(member_ids, '{}'::bigint[]))
      AND users.approved = true
    ON CONFLICT DO NOTHING;

    RETURN new_group_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.add_chat_group_member(
    target_group_id bigint,
    target_user_id bigint
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
    current_app_user_id bigint;
    current_username text;
    added_username text;
BEGIN
    SELECT id, username INTO current_app_user_id, current_username
    FROM public.app_users
    WHERE auth_user_id = auth.uid() AND approved = true;

    SELECT username INTO added_username
    FROM public.app_users
    WHERE id = target_user_id AND approved = true;

    IF current_app_user_id IS NULL OR added_username IS NULL THEN
        RAISE EXCEPTION 'Benutzer nicht gefunden';
    END IF;

    IF NOT public.is_chat_group_member(target_group_id) THEN
        RAISE EXCEPTION 'Du bist kein Mitglied dieser Gruppe';
    END IF;

    IF EXISTS (
        SELECT 1 FROM public.chat_group_members
        WHERE group_id = target_group_id AND user_id = target_user_id
    ) THEN
        RAISE EXCEPTION 'Dieser Benutzer ist bereits Mitglied der Gruppe';
    END IF;

    INSERT INTO public.chat_group_messages (group_id, sender_id, message)
    VALUES (
        target_group_id,
        current_app_user_id,
        current_username || ' hat ' || added_username || ' zur Gruppe hinzugefügt'
    );

    INSERT INTO public.chat_group_members (group_id, user_id)
    VALUES (target_group_id, target_user_id);
END;
$function$;

